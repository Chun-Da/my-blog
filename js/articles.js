      <p>就在这段路上，终于碰上了野生大师兄。一路上猴子不少，但它们并未对我们实施抢劫（但也确实见到它们抢劫其他游客），可能是因为我们手上有 4 支登山杖，也可能是因为夜色将近早已饱餐一顿准备入睡。从仙峰寺出发之后游客明显变少了，随着天色渐晚，山里明显安静下来，游客的声音逐渐消失，只剩下稀疏的脚步声、登山杖敲在石板上的声音，以及偶尔从树林里传来的诡异动静。如果说白天的峨眉山是热闹的，夜晚的峨眉山则是考验人的。从仙峰寺出发之后不久其实就能够看到高处的雷洞坪了，但望山跑死马，这段看起来一点不起眼的路，我们还要走大概 5 个小时。</p>

